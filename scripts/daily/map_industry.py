# Read stocks.json
with open(r'C:\Users\chenx\OneDrive\DialyNotes\Trading\scripts\stocks.json', 'r', encoding='utf-8') as f:
    data = json.load(f)

stats = {'mapped': 0, 'override': 0, 'unmapped': 0, 'unmapped_items': []}

for stock in data['stocks']:
    code = stock['code']
    layer = str(stock['layer'])
    sub = stock.get('sub', '')

    if code in CODE_OVERRIDES:
        ind1, ind2 = CODE_OVERRIDES[code]
        stock['em_industry1'] = ind1
        stock['em_industry2'] = ind2
        stats['override'] += 1
        stats['mapped'] += 1
        continue

    key = (layer, sub)
    if key in INDUSTRY_MAP:
        ind1, ind2 = INDUSTRY_MAP[key]
        stock['em_industry1'] = ind1
        stock['em_industry2'] = ind2
        stats['mapped'] += 1
    else:
        stats['unmapped'] += 1
        stats['unmapped_items'].append(f"{stock['name']}({code}) L{layer}/{sub}")
        stock['em_industry1'] = "综合"
        stock['em_industry2'] = "综合"

data['meta']['em_industry_version'] = "东方财富行业分类"
data['meta']['updated'] = "2026-05-29"

with open(r'C:\Users\chenx\OneDrive\DialyNotes\Trading\scripts\stocks.json', 'w', encoding='utf-8') as f:
    json.dump(data, f, ensure_ascii=False, indent=2)

print(f"=== 映射完成 ===")
